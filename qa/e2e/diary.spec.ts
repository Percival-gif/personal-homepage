import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
const bodyText='## 自动验收临时记录\n仅用于验证本地保存与恢复。';
async function openNotebook(page: import('@playwright/test').Page){
  await page.goto('/#/diary');
  const disclosure=page.getByRole('button',{name:'我明白了，开始写',exact:true});
  await expect(page.getByTestId('diary-ready')).toBeVisible();
  await page.waitForFunction(()=>document.querySelector('[data-testid=diary-ready]')?.getAttribute('data-diary-ready')==='true'||Array.from(document.querySelectorAll('button')).some(b=>b.textContent==='我明白了，开始写'));
  if(await disclosure.isVisible())await disclosure.click();
  await expect(page.getByTestId('diary-ready')).toHaveAttribute('data-diary-ready','true');
  const start=page.getByRole('button',{name:'开始写',exact:true});
  if(await start.isVisible())await start.click();
  await expect(page.getByTestId('diary-body')).toBeVisible();
}
test('autosave, reload, sealed metadata, unseal and local ZIP roundtrip',async({page})=>{
  await openNotebook(page);
  await page.getByTestId('diary-body').fill(bodyText);
  await page.getByRole('radio',{name:'雨',exact:true}).check();
  await page.getByRole('radio',{name:'平静',exact:true}).check();
  await page.getByLabel('标签 · 最多八个',{exact:true}).fill('验收');
  await page.getByLabel('标签 · 最多八个',{exact:true}).press('Enter');
  await expect(page.getByTestId('diary-save-status')).toContainText('已保存');
  await page.reload();
  await expect(page.getByTestId('diary-body')).toHaveValue(bodyText);
  await page.getByRole('button',{name:'封存今天',exact:true}).click();
  await expect(page.getByTestId('diary-body')).toBeDisabled();
  await expect(page.getByTestId('diary-date')).toBeDisabled();
  await expect(page.getByRole('button',{name:'删除这篇',exact:true})).toBeDisabled();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出全部 ZIP',exact:true}).click();
  const zip=await downloadPromise;const path=await zip.path();expect(path).toBeTruthy();
  const backup={name:zip.suggestedFilename(),mimeType:'application/zip',buffer:await readFile(path!)};
  await page.getByRole('button',{name:'解除封存',exact:true}).click();
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await expect(page.getByTestId('diary-body')).toBeDisabled();
  await page.getByRole('button',{name:'解除封存',exact:true}).click();
  await page.getByRole('button',{name:'确认解除封存',exact:true}).click();
  await expect(page.getByTestId('diary-body')).toBeEnabled();
  await page.getByTestId('diary-import-file').setInputFiles(backup);
  await expect(page.getByTestId('import-preview')).toBeVisible();
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await expect(page.getByTestId('import-preview')).toBeHidden();
  await page.getByRole('button',{name:'删除这篇',exact:true}).click();
  await page.getByRole('button',{name:'确认删除',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.getByTestId('diary-import-file').setInputFiles(backup);
  await expect(page.getByTestId('import-preview')).toBeVisible();
  await page.getByRole('button',{name:'确认导入',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.getByRole('button',{name:'今日',exact:true}).click();
  await expect(page.getByTestId('diary-body')).toHaveValue(bodyText);
  await expect(page.getByTestId('diary-body')).toBeDisabled();
  await expect(page.getByRole('radio',{name:'雨',exact:true})).toBeChecked();
  await expect(page.getByRole('radio',{name:'平静',exact:true})).toBeChecked();
  await expect(page.getByText('验收',{exact:true})).toBeVisible();
});
test('settled writing and exporting send zero requests and work offline',async({page,context})=>{
  await openNotebook(page);
  await page.evaluate(()=>document.fonts.ready);
  const requests:string[]=[];
  page.on('request',r=>requests.push(r.url()));
  await context.setOffline(true);
  await page.getByTestId('diary-body').fill(bodyText);
  await page.getByTestId('diary-save').click();
  await expect(page.getByTestId('diary-save-status')).toContainText('已保存');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出全部 ZIP',exact:true}).click();
  await downloadPromise;
  expect(requests).toEqual([]);
});
